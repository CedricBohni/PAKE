"""Modular arithmetic over a prime-order subgroup.

The protocol works in the subgroup of order ``q`` of Z_p^*, generated by ``g``,
where p = 2q + 1 is a safe prime. Secrets and shares live in Z_q (``sub=True``),
their exponentiations g^x live in Z_p.

Two groups are built in:
    MODP_2048  RFC 3526 group 14, the default.
    DEMO_GROUP an 18-bit toy group. Fast and easy to read, but offers no security.
"""

import secrets
from dataclasses import dataclass


@dataclass(frozen=True)
class Group:
    name: str
    p: int  # safe prime
    q: int  # (p - 1) / 2, the subgroup order
    g: int  # generator of the order-q subgroup

    def __post_init__(self) -> None:
        if self.p != 2 * self.q + 1:
            raise ValueError("p must equal 2q + 1")
        if self.g in (0, 1) or pow(self.g, self.q, self.p) != 1:
            raise ValueError("g must generate the order-q subgroup")


