"""Modular arithmetic over a prime-order subgroup.

The protocol works in the subgroup of order ``q`` of Z_p^*, generated by ``g``.
Secrets and shares live in Z_q (``sub=True``), their exponentiations g^x live in Z_p.

NOTE: the default parameters are deliberately tiny so the protocol is fast and easy
to inspect. They offer no real security.
"""

import random

from sympy import mod_inverse

# Toy parameters: p = 2q + 1 (safe prime), g generates the order-q subgroup.
p = 209459
q = 104729
g = 4


class ModularArithmetic:
    """
    The ModularArithmetic class provides methods for performing modular arithmetic operations.

    Key Components:
        PRIME: The main prime modulus used for modular operations.
        sub_PRIME: A smaller prime modulus representing a subgroup of the main group.
        generator: A base value used for modular exponentiation and pseudo-random generation.
        sub Boolean:
        sub=True: Indicates operations should use the subgroup modulus (sub_PRIME).
        sub=False: Indicates operations should use the main prime modulus (PRIME).
        This flexibility allows the class to perform operations in either the main group or its subgroup, depending on the context.
    """

    def __init__(self, generator: int = g, PRIME: int = p, sub_PRIME: int = q) -> None:
        self.generator = generator
        self.PRIME = PRIME
        self.sub_PRIME = sub_PRIME

    def mod(self, a: int, sub: bool = False) -> int:
        if sub:
            return a % self.sub_PRIME
        else:
            return a % self.PRIME

    def generate_random_int(self, sub: bool = False) -> int:
        if sub:
            return random.randint(1, (self.sub_PRIME - 1))
        else:
            return random.randint(1, (self.PRIME - 1))

    def modular_generator_exponentiation(self, value: int, sub: bool = False) -> int:
        if sub:
            return pow(self.generator, value, self.sub_PRIME)
        else:
            return pow(self.generator, value, self.PRIME)

    def modular_exponentiation(self, base: int, exponent: int, sub: bool = False) -> int:
        if sub:
            return pow(base, exponent, self.sub_PRIME)
        else:
            return pow(base, exponent, self.PRIME)

    def modular_inverse(self, a: int, sub: bool = False) -> int:
        if sub:
            return mod_inverse(a, self.sub_PRIME)
        else:
            return mod_inverse(a, self.PRIME)

    def modular_addition(self, a: int, b: int, sub: bool = False) -> int:
        if sub:
            return (a + b) % self.sub_PRIME
        else:
            return (a + b) % self.PRIME

    def modular_subtraction(self, a: int, b: int, sub: bool = False) -> int:
        if sub:
            return (a - b) % self.sub_PRIME
        else:
            return (a - b) % self.PRIME

    def modular_multiplication(self, a: int, b: int, sub: bool = False) -> int:
        if sub:
            return (a * b) % self.sub_PRIME
        else:
            return (a * b) % self.PRIME

    def modular_division(self, a: int, b: int, sub: bool = False) -> int:
        if sub:
            return self.modular_multiplication(a, self.modular_inverse(b, sub=True), sub=True)
        else:
            return self.modular_multiplication(a, self.modular_inverse(b))

    def pseudo_random_generator(self, seed: int, sub: bool = False) -> str:
        if sub:
            value = pow(self.generator, seed, self.sub_PRIME)
        else:
            value = pow(self.generator, seed, self.PRIME)

        output = value.to_bytes((value.bit_length() + 7) // 8, 'big')

        return output.hex()
