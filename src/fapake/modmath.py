MODP_2048 = Group("modp2048", _MODP_2048_P, (_MODP_2048_P - 1) // 2, 2)
DEMO_GROUP = Group("demo", 209459, 104729, 4)
DEFAULT_GROUP = MODP_2048
GROUPS = {group.name: group for group in (MODP_2048, DEMO_GROUP)}


class ModularArithmetic:
    """
    Modular arithmetic in a Group.

    sub=True:  operations modulo the subgroup order q (exponents, shares).
    sub=False: operations modulo the prime p (group elements).
    """

    def __init__(self, group: Group = DEFAULT_GROUP) -> None:
        self.group = group
        self.generator = group.g
        self.PRIME = group.p
        self.sub_PRIME = group.q

    def _modulus(self, sub: bool) -> int:
        return self.sub_PRIME if sub else self.PRIME

    def mod(self, a: int, sub: bool = False) -> int:
        return a % self._modulus(sub)

    def generate_random_int(self, sub: bool = False) -> int:
        """Uniform in [1, modulus - 1], from a cryptographically secure source."""
        return secrets.randbelow(self._modulus(sub) - 1) + 1

    def modular_generator_exponentiation(self, value: int, sub: bool = False) -> int:
        return pow(self.generator, value, self._modulus(sub))

    def modular_exponentiation(self, base: int, exponent: int, sub: bool = False) -> int:
        return pow(base, exponent, self._modulus(sub))

    def modular_inverse(self, a: int, sub: bool = False) -> int:
        return pow(a, -1, self._modulus(sub))

    def modular_addition(self, a: int, b: int, sub: bool = False) -> int:
        return (a + b) % self._modulus(sub)

    def modular_subtraction(self, a: int, b: int, sub: bool = False) -> int:
        return (a - b) % self._modulus(sub)

    def modular_multiplication(self, a: int, b: int, sub: bool = False) -> int:
        return (a * b) % self._modulus(sub)

    def modular_division(self, a: int, b: int, sub: bool = False) -> int:
        return self.modular_multiplication(a, self.modular_inverse(b, sub), sub)
